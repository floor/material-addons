import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const header = "// Generated by the addons build from the stepper element contract.";
const factories = { react: "React", vue: "Vue", solid: "Solid" };

export function adapterEntry(framework) {
  const factory = factories[framework];
  const prefix = framework === "vue" ? "M" : "";
  return `${framework === "react" ? '"use client";\n' : ""}${header}
import "material-addons/elements/css/stepper";
import { create${factory}Stepper, create${factory}Step } from "../adapters/${framework}";
export const ${prefix}Stepper = /*#__PURE__*/ create${factory}Stepper();
export const ${prefix}Step = /*#__PURE__*/ create${factory}Step();
export type { ${factory}StepperProps${framework === "vue" ? ", VueStepperEmits" : `, ${factory}StepProps`} } from "../adapters/${framework}";
export type { StepperElementEventMap } from "../elements/stepper";
`;
}

const stepper = `<!-- Generated by the addons build from the stepper element contract. -->
<script lang="ts">
  import "material-addons/elements/css/stepper";
  import {
    attributes, connectStepper, hostProps, initialValue, stepperHost, svelteEventKeys, tag,
    type SvelteStepperProps,
  } from "./runtime.mjs";
  import type { StepperElement } from "material-addons/elements/stepper";

  let { children, value = $bindable(), ...props }: SvelteStepperProps = $props();
  let element = $state<StepperElement | null>(null);
  export { element };
  const set = (next: string | null) => { value = next; };
  const host = $derived(hostProps(stepperHost, props, [...svelteEventKeys, "defaultValue"]));
</script>

<svelte:element
  this={tag("stepper")}
  {...host}
  {...attributes(stepperHost, props, true)}
  value={typeof window === "undefined" ? initialValue({ ...props, value }) ?? undefined : undefined}
  bind:this={element}
  use:connectStepper={{ props: { ...props, value }, set }}
>{@render children?.()}</svelte:element>
`;

const step = `<!-- Generated by the addons build from the stepper element contract. -->
<script lang="ts">
  import { attributes, hostProps, stepHost, tag, type SvelteStepProps } from "./runtime.mjs";
  let { children, ...props }: SvelteStepProps = $props();
</script>

<svelte:element this={tag("step")} {...hostProps(stepHost, props)} {...attributes(stepHost, props)}>
  {@render children?.()}
</svelte:element>
`;

export async function writeSvelteAdapters(outdir) {
  await mkdir(outdir, { recursive: true });
  const write = (file, source) => writeFile(join(outdir, file), source);
  const exports = 'export { default as Stepper } from "./Stepper.svelte";\nexport { default as Step } from "./Step.svelte";\n';
  await Promise.all([
    write("Stepper.svelte", stepper),
    write("Step.svelte", step),
    write("index.js", exports),
    write("index.d.ts", exports + 'export type { SvelteStepperProps, SvelteStepProps, SvelteStepperEvents } from "../adapters/svelte";\nexport type { StepperElementEventMap } from "../elements/stepper";\n'),
    write("Stepper.svelte.d.ts", `import type { Component } from "svelte";
import type { StepperElement } from "../elements/stepper";
import type { SvelteStepperProps } from "../adapters/svelte";
declare const Stepper: Component<SvelteStepperProps, { readonly element: StepperElement | null }, "value">;
export default Stepper;
`),
    write("Step.svelte.d.ts", `import type { Component } from "svelte";
import type { SvelteStepProps } from "../adapters/svelte";
declare const Step: Component<SvelteStepProps>;
export default Step;
`),
  ]);
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  let stale = false;
  for (const framework of Object.keys(factories)) {
    const directory = new URL(`../src/${framework}/`, import.meta.url);
    const file = new URL("index.ts", directory);
    const expected = adapterEntry(framework);
    if (check) {
      if ((await Bun.file(file).text().catch(() => "")) !== expected) {
        console.error(`${file.pathname} is stale. Run bun run adapters:generate.`);
        stale = true;
      }
    } else {
      await mkdir(directory, { recursive: true });
      await writeFile(file, expected);
    }
  }
  if (stale) process.exitCode = 1;
}
