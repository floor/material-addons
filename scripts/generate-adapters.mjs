import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const header = "// Generated by the addons build from the element contracts.";
const factories = { react: "React", vue: "Vue", solid: "Solid" };

export function adapterEntry(framework) {
  const factory = factories[framework];
  const prefix = framework === "vue" ? "M" : "";
  return `${framework === "react" ? '"use client";\n' : ""}${header}
import "material-addons/elements/css/stepper";
import { create${factory}Stepper, create${factory}Step } from "../adapters/${framework}";
export const ${prefix}Stepper = /*#__PURE__*/ create${factory}Stepper();
export const ${prefix}Step = /*#__PURE__*/ create${factory}Step();
export type { ${factory}StepperProps${framework === "vue" ? ", VueStepperEmits" : `, ${factory}StepProps`} } from "../adapters/${framework}";
export type { StepperElementEventMap } from "../elements/stepper";
import "material-addons/elements/css/autocomplete";
import { create${factory}Autocomplete, create${factory}AutocompleteOption } from "../adapters/autocomplete/${framework}";
export const ${prefix}Autocomplete = /*#__PURE__*/ create${factory}Autocomplete();
export const ${prefix}AutocompleteOption = /*#__PURE__*/ create${factory}AutocompleteOption();
export type { ${factory}AutocompleteProps, ${factory === "Vue" ? "VueAutocompleteEmits" : `${factory}AutocompleteOptionProps`} } from "../adapters/autocomplete/${framework}";
export type { AutocompleteElementEventMap } from "../elements/autocomplete";
`;
}

function svelteModel({ tag, name, host, runtime }) {
  return `<!-- Generated by the addons build from the ${tag} element contract. -->
<script lang="ts">
  import "material-addons/elements/css/${tag}";
  import {
    attributes, connect${name}, hostProps, initialValue, ${host}, svelteEventKeys, tag,
    type Svelte${name}Props,
  } from "./${runtime}";
  import type { ${name}Element } from "material-addons/elements/${tag}";

  let { children, value = $bindable(), ...props }: Svelte${name}Props = $props();
  let element = $state<${name}Element | null>(null);
  export { element };
  const set = (next: string | null) => { value = next; };
  const host = $derived(hostProps(${host}, props, [...svelteEventKeys, "defaultValue"]));
</script>

<svelte:element
  this={tag("${tag}")}
  {...host}
  {...attributes(${host}, props, true)}
  value={typeof window === "undefined" ? initialValue({ ...props, value }) ?? undefined : undefined}
  bind:this={element}
  use:connect${name}={{ props: { ...props, value }, set }}
>{@render children?.()}</svelte:element>
`;
}

function svelteDeclaration({ tag, name, host, runtime }) {
  return `<!-- Generated by the addons build from the ${tag} element contract. -->
<script lang="ts">
  import { attributes, hostProps, ${host}, tag, type Svelte${name}Props } from "./${runtime}";
  let { children, ...props }: Svelte${name}Props = $props();
</script>

<svelte:element this={tag("${tag}")} {...hostProps(${host}, props)} {...attributes(${host}, props)}>
  {@render children?.()}
</svelte:element>
`;
}

const svelteSpecs = [
  {
    tag: "stepper", name: "Stepper", host: "stepperHost", runtime: "runtime.mjs", types: "../adapters/svelte",
    declaration: { tag: "step", name: "Step", host: "stepHost" },
  },
  {
    tag: "autocomplete", name: "Autocomplete", host: "autocompleteHost",
    runtime: "autocomplete-runtime.mjs", types: "../adapters/autocomplete/svelte",
    declaration: { tag: "autocomplete-option", name: "AutocompleteOption", host: "optionHost" },
  },
];

export async function writeSvelteAdapters(outdir) {
  await mkdir(outdir, { recursive: true });
  const write = (file, source) => writeFile(join(outdir, file), source);
  let runtimeExports = "";
  let typeExports = "";
  const files = [];
  for (const spec of svelteSpecs) {
    const { name, tag, types, runtime, declaration } = spec;
    for (const component of [name, declaration.name]) {
      runtimeExports += `export { default as ${component} } from "./${component}.svelte";\n`;
    }
    typeExports += `export type { Svelte${name}Props, Svelte${declaration.name}Props, Svelte${name}Events } from "${types}";\n`;
    typeExports += `export type { ${name}ElementEventMap } from "../elements/${tag}";\n`;
    files.push(
      write(`${name}.svelte`, svelteModel(spec)),
      write(`${declaration.name}.svelte`, svelteDeclaration({ ...declaration, runtime })),
      write(`${name}.svelte.d.ts`, `import type { Component } from "svelte";
import type { ${name}Element } from "../elements/${tag}";
import type { Svelte${name}Props } from "${types}";
declare const ${name}: Component<Svelte${name}Props, { readonly element: ${name}Element | null }, "value">;
export default ${name};
`),
      write(`${declaration.name}.svelte.d.ts`, `import type { Component } from "svelte";
import type { Svelte${declaration.name}Props } from "${types}";
declare const ${declaration.name}: Component<Svelte${declaration.name}Props>;
export default ${declaration.name};
`),
    );
  }
  await Promise.all([...files, write("index.js", runtimeExports), write("index.d.ts", runtimeExports + typeExports)]);
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  let stale = false;
  for (const framework of Object.keys(factories)) {
    const directory = new URL(`../src/${framework}/`, import.meta.url);
    const file = new URL("index.ts", directory);
    const expected = adapterEntry(framework);
    if (check) {
      if ((await Bun.file(file).text().catch(() => "")) !== expected) {
        console.error(`${file.pathname} is stale. Run bun run adapters:generate.`);
        stale = true;
      }
    } else {
      await mkdir(directory, { recursive: true });
      await writeFile(file, expected);
    }
  }
  if (stale) process.exitCode = 1;
}
