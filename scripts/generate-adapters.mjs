export async function writeSvelteAdapters(outdir) {
  await mkdir(outdir, { recursive: true });
  const write = (file, source) => writeFile(join(outdir, file), source);
  let runtimeExports = "";
  let typeExports = "";
  const files = [];
  for (const spec of svelteSpecs) {
    const { name, tag, types, runtime, declaration } = spec;
    for (const component of [name, declaration.name]) {
      runtimeExports += `export { default as ${component} } from "./${component}.svelte";\n`;
    }
    typeExports += `export type { Svelte${name}Props, Svelte${declaration.name}Props, Svelte${name}Events } from "${types}";\n`;
    typeExports += `export type { ${name}ElementEventMap } from "../elements/${tag}";\n`;
    files.push(
      write(`${name}.svelte`, svelteModel(spec)),
      write(`${declaration.name}.svelte`, svelteDeclaration({ ...declaration, runtime })),
      write(`${name}.svelte.d.ts`, `import type { Component } from "svelte";
import type { ${name}Element } from "../elements/${tag}";
import type { Svelte${name}Props } from "${types}";
declare const ${name}: Component<Svelte${name}Props, { readonly element: ${name}Element | null }, "value">;
export default ${name};
`),
      write(`${declaration.name}.svelte.d.ts`, `import type { Component } from "svelte";
import type { Svelte${declaration.name}Props } from "${types}";
declare const ${declaration.name}: Component<Svelte${declaration.name}Props>;
export default ${declaration.name};
`),
    );
  }
  runtimeExports += 'export { default as ExpansionPanel } from "./ExpansionPanel.svelte";\nexport { default as Accordion } from "./Accordion.svelte";\n';
  typeExports += 'export type { SvelteExpansionPanelProps, SvelteAccordionProps } from "../adapters/svelte-expansion";\nexport type { ExpansionPanelElementEventMap } from "../elements/expansion-panel";\n';
  runtimeExports += 'export { default as Avatar } from "./Avatar.svelte";\n';
  typeExports += 'export type { SvelteAvatarProps } from "../adapters/avatar/svelte";\n';
  typeExports += 'export type { AvatarElementEventMap } from "../elements/avatar";\n';
  await Promise.all([
    ...files,
    write("Avatar.svelte", avatar),
    write("Avatar.svelte.d.ts", `import type { Component } from "svelte";
import type { SvelteAvatarProps } from "../adapters/avatar/svelte";
declare const Avatar: Component<SvelteAvatarProps>;
export default Avatar;
`),
    write("ExpansionPanel.svelte", expansionPanel),
    write("Accordion.svelte", accordion),
    write("ExpansionPanel.svelte.d.ts", `import type { Component } from "svelte";
import type { ExpansionPanelElement } from "../elements/expansion-panel";
import type { SvelteExpansionPanelProps } from "../adapters/svelte-expansion";
declare const ExpansionPanel: Component<SvelteExpansionPanelProps, { readonly element: ExpansionPanelElement | null }>;
export default ExpansionPanel;
`),
    write("Accordion.svelte.d.ts", `import type { Component } from "svelte";
import type { AccordionElement } from "../elements/expansion-panel";
import type { SvelteAccordionProps } from "../adapters/svelte-expansion";
declare const Accordion: Component<SvelteAccordionProps, { readonly element: AccordionElement | null }, "value">;
export default Accordion;
`),
    write("index.js", runtimeExports),
    write("index.d.ts", runtimeExports + typeExports),
  ]);
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  let stale = false;
  for (const framework of Object.keys(factories)) {
    const directory = new URL(`../src/${framework}/`, import.meta.url);
    const file = new URL("index.ts", directory);
    const expected = adapterEntry(framework);
    if (check) {
      if ((await Bun.file(file).text().catch(() => "")) !== expected) {
        console.error(`${file.pathname} is stale. Run bun run adapters:generate.`);
        stale = true;
      }
    } else {
      await mkdir(directory, { recursive: true });
      await writeFile(file, expected);
    }
  }
  if (stale) process.exitCode = 1;
}
