import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const header = "// Generated by the addons build from the element contracts.";
const factories = { react: "React", vue: "Vue", solid: "Solid" };

export function adapterEntry(framework) {
  const factory = factories[framework];
  const prefix = framework === "vue" ? "M" : "";
  return `${framework === "react" ? '"use client";\n' : ""}${header}
import "material-addons/elements/css/stepper";
import "material-addons/elements/css/expansion-panel";
import { create${factory}Stepper, create${factory}Step } from "../adapters/${framework}";
import { create${factory}ExpansionPanel, create${factory}Accordion } from "../adapters/${framework}-expansion";
export const ${prefix}Stepper = /*#__PURE__*/ create${factory}Stepper();
export const ${prefix}Step = /*#__PURE__*/ create${factory}Step();
export const ${prefix}ExpansionPanel = /*#__PURE__*/ create${factory}ExpansionPanel();
export const ${prefix}Accordion = /*#__PURE__*/ create${factory}Accordion();
export type { ${factory}StepperProps${framework === "vue" ? ", VueStepperEmits" : `, ${factory}StepProps`} } from "../adapters/${framework}";
export type { ${factory}ExpansionPanelProps, ${factory}AccordionProps } from "../adapters/${framework}-expansion";
export type { StepperElementEventMap } from "../elements/stepper";
export type { ExpansionPanelElementEventMap } from "../elements/expansion-panel";
`;
}

