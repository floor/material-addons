function svelteModel({ tag, name, host, runtime }) {
  return `<!-- Generated by the addons build from the ${tag} element contract. -->
<script lang="ts">
  import "material-addons/elements/css/${tag}";
  import {
    attributes, connect${name}, hostProps, initialValue, ${host}, svelteEventKeys, tag,
    type Svelte${name}Props,
  } from "./${runtime}";
  import type { ${name}Element } from "material-addons/elements/${tag}";

  let { children, value = $bindable(), ...props }: Svelte${name}Props = $props();
  let element = $state<${name}Element | null>(null);
  export { element };
  const set = (next: string | null) => { value = next; };
  const host = $derived(hostProps(${host}, props, [...svelteEventKeys, "defaultValue"]));
</script>

<svelte:element
  this={tag("${tag}")}
  {...host}
  {...attributes(${host}, props, true)}
  value={typeof window === "undefined" ? initialValue({ ...props, value }) ?? undefined : undefined}
  bind:this={element}
  use:connect${name}={{ props: { ...props, value }, set }}
>{@render children?.()}</svelte:element>
`;
}

function svelteDeclaration({ tag, name, host, runtime }) {
  return `<!-- Generated by the addons build from the ${tag} element contract. -->
<script lang="ts">
  import { attributes, hostProps, ${host}, tag, type Svelte${name}Props } from "./${runtime}";
  let { children, ...props }: Svelte${name}Props = $props();
</script>

<svelte:element this={tag("${tag}")} {...hostProps(${host}, props)} {...attributes(${host}, props)}>
  {@render children?.()}
</svelte:element>
`;
}

